#!/usr/bin/env node
/**
 * HK2026 backend OpenAPI client — same flow as Bratislava’s openapi-clients package:
 * https://github.com/bratislava/konto.bratislava.sk/tree/master/openapi-clients
 *
 * 1. openapi-generator-cli (typescript-axios)
 * 2. Remove docs/ (see removeDocsAndCleanupFiles in their generateClient.ts)
 * 3. Emit client.ts by merging *ApiFactory spreads (see generateClientFile)
 * 4. Re-export client from index.ts (see updateIndexFile)
 *
 * Requires a JDK.
 *
 * Usage:
 *   npm run generate:api:local
 *   npm run generate:api
 *   npm run generate:api -- --spec-url ./openapi.json
 */

import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "..");
const outputDir = path.join(projectRoot, "api", "generated");

function parseCli() {
  const { values } = parseArgs({
    options: {
      "local-url": { type: "string", default: "localhost:8000" },
      "spec-url": { type: "string" },
    },
    allowPositionals: false,
  });
  return values;
}

function resolveInputUrl(values) {
  const fromEnv = process.env.OPENAPI_SPEC_URL?.trim();
  const specUrl = values["spec-url"]?.trim() || fromEnv;
  if (specUrl) {
    if (/^https?:\/\//i.test(specUrl) || /^file:/i.test(specUrl)) {
      return specUrl;
    }
    return path.resolve(projectRoot, specUrl);
  }
  const host = values["local-url"]?.trim() || "localhost:8000";
  const normalized = host.startsWith("http://") || host.startsWith("https://")
    ? host
    : `http://${host}`;
  const base = normalized.replace(/\/$/, "");
  return `${base}/openapi.json`;
}

/** Mirrors openapi-clients/scripts/generateClient.ts removeDocsAndCleanupFiles */
function removeDocsAndCleanupFiles() {
  const docsDir = path.join(outputDir, "docs");
  fs.rmSync(docsDir, { recursive: true, force: true });

  const filesPath = path.join(outputDir, ".openapi-generator", "FILES");
  try {
    const filesContent = fs.readFileSync(filesPath, "utf8");
    const filtered = filesContent
      .split("\n")
      .filter((line) => !line.startsWith("docs/"))
      .join("\n");
    fs.writeFileSync(filesPath, filtered, "utf8");
  } catch {
    // optional
  }
}

/** Mirrors openapi-clients/scripts/generateClient.ts generateClientFile (factory merge). */
function generateClientFile() {
  const apiPath = path.join(outputDir, "api.ts");
  const content = fs.readFileSync(apiPath, "utf8");
  const factoryRegex = /export const (\w+Factory)/g;
  const factories = [...content.matchAll(factoryRegex)].map((m) => m[1]);

  if (factories.length === 0) {
    throw new Error("No *ApiFactory exports found in api.ts — OpenAPI generator output may have changed.");
  }

  const factoryImports = factories.join(",\n  ");
  const spreads = factories.map((f) => `    ...${f}(...args),`).join("\n");

  const clientTs = `/* eslint-disable */
/**
 * Merged axios API client — generated by scripts/generate-backend-client.mjs
 * (same pattern as https://github.com/bratislava/konto.bratislava.sk/blob/master/openapi-clients/scripts/generateClient.ts).
 */
import {
  ${factoryImports},
} from "./api";
import { Configuration, type ConfigurationParameters } from "./configuration";
import type { AxiosInstance } from "axios";

/** Default FastAPI base URL for local development. */
export const BACKEND_BASE_URL = "http://127.0.0.1:8000" as const;

export type ClientConfig = {
  basePath?: string;
  configurationParameters?: ConfigurationParameters;
  axios?: AxiosInstance;
};

export function createBackendClient({
  basePath = BACKEND_BASE_URL,
  configurationParameters = {},
  axios,
}: ClientConfig = {}) {
  const configuration = new Configuration(configurationParameters);
  const args = [configuration, basePath, axios] as const;

  return {
${spreads}
  };
}

export type BackendClient = ReturnType<typeof createBackendClient>;

export const backendClient = createBackendClient();
`;

  fs.writeFileSync(path.join(outputDir, "client.ts"), clientTs, "utf8");
}

/** Mirrors openapi-clients/scripts/generateClient.ts updateIndexFile */
function updateIndexFile() {
  const indexPath = path.join(outputDir, "index.ts");
  let indexSrc = fs.readFileSync(indexPath, "utf8");
  if (indexSrc.includes('export * from "./client"')) {
    return;
  }
  const updated = indexSrc.replace(
    /export \* from "\.\/configuration";?/,
    'export * from "./configuration";\nexport * from "./client";',
  );
  if (updated === indexSrc) {
    throw new Error(
      'Could not patch index.ts: expected export * from "./configuration" — generator layout changed.',
    );
  }
  fs.writeFileSync(indexPath, updated, "utf8");
}

function main() {
  const values = parseCli();
  const inputUrl = resolveInputUrl(values);

  console.log(`OpenAPI input: ${inputUrl}`);
  console.log(`Output: ${path.relative(projectRoot, outputDir)}`);

  fs.rmSync(outputDir, { recursive: true, force: true });
  fs.mkdirSync(outputDir, { recursive: true });

  const cmd = [
    "npx",
    "@openapitools/openapi-generator-cli",
    "generate",
    "-i",
    inputUrl,
    "-g",
    "typescript-axios",
    "-o",
    outputDir,
    "--skip-validate-spec",
    "--additional-properties",
    [
      "supportsES6=true",
      "withInterfaces=true",
      "enumPropertyNaming=original",
      "modelPropertyNaming=original",
    ].join(","),
  ];

  execSync(cmd.join(" "), {
    cwd: projectRoot,
    stdio: "inherit",
    env: process.env,
  });

  removeDocsAndCleanupFiles();
  generateClientFile();
  updateIndexFile();

  console.log(
    'Done. Import facade + models from one module, e.g. import { createBackendClient, type BackendClient, type GroupCreate } from "@/api/generated".',
  );
}

main();
